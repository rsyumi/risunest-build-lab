// Writes crates/core/render/src/tables.rs from the packages markdown-it 14.3.2 resolves: the `entities` HTML decode trie
// and the code points `isPunctChar` accepts (uc.micro `P` or `S`). Run `node benchmarks/rust-core-oracles/render-markdown.tables.mjs`
// after a markdown-it dependency update; render-markdown.oracle.test.ts fails while the committed file differs.
import { readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

// Built from path strings: the happy-dom environment of the oracle test replaces the global URL.
const here = dirname(fileURLToPath(import.meta.url))
export const tablesPath = resolve(here, '../../crates/core/render/src/tables.rs')

// markdown-it's own dependencies, resolved beside its real package directory as Node resolves them for it.
function dependencyDirectory(name) {
    const markdownIt = realpathSync(dirname(createRequire(import.meta.url).resolve('markdown-it/package.json')))
    return join(markdownIt, '..', name)
}
const version = (directory) => JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8')).version

function rows(values, perRow) {
    const lines = []
    for (let index = 0; index < values.length; index += perRow) lines.push(`    ${values.slice(index, index + perRow).join(', ')},`)
    return lines.join('\n')
}

export async function renderTables() {
    const entities = dependencyDirectory('entities')
    const ucmicro = dependencyDirectory('uc.micro')
    const tree = (await import(pathToFileURL(join(entities, 'lib/esm/generated/decode-data-html.js')).href)).default
    const { P, S } = await import(pathToFileURL(join(ucmicro, 'index.mjs')).href)
    // markdown-it `isPunctCharCode`: `fromCodePoint` gives a lone unit below 0x10000, so lone surrogates are tested too.
    const ranges = []
    let open = -1
    for (let code = 0; code <= 0x110000; code++) {
        const inside = code <= 0x10ffff && (() => {
            const text = code > 0xffff ? String.fromCodePoint(code) : String.fromCharCode(code)
            return P.test(text) || S.test(text)
        })()
        if (inside && open < 0) open = code
        if (!inside && open >= 0) {
            ranges.push(`(0x${open.toString(16)}, 0x${(code - 1).toString(16)})`)
            open = -1
        }
    }
    return [
        `//! Generated by \`benchmarks/rust-core-oracles/render-markdown.tables.mjs\` from entities ${version(entities)} and uc.micro ${version(ucmicro)}; do not edit.`,
        '',
        '/// `htmlDecodeTree` of entities (`lib/esm/generated/decode-data-html.js`), the trie `decodeHTML` and `decodeHTMLStrict` walk.',
        `pub(crate) static HTML_DECODE_TREE: [u16; ${tree.length}] = [`,
        rows(Array.from(tree, (unit) => String(unit)), 20),
        '];',
        '',
        '/// Inclusive code point ranges where markdown-it `isPunctCharCode` holds (uc.micro `P` or `S`, tested without the `u` flag).',
        `pub(crate) static PUNCT_RANGES: [(u32, u32); ${ranges.length}] = [`,
        rows(ranges, 6),
        '];',
        '',
    ].join('\n')
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
    writeFileSync(tablesPath, await renderTables())
}
